using System;
using System.Collections.Generic;
using UnityEngine;

namespace RoboFactory.Packing
{
    public enum ItemKind { Mug, Bottle, Can, Ball, ToyCar, Book, GiftBox }

    /// <summary>Visible manufacturing defect (what the scan has to find). None = good item.</summary>
    public enum ItemDefect { None, Cracked, Dented, Stained, Broken }

    /// <summary>
    /// A small product travelling on the packing conveyor. The simulation knows its true kind and defect (to check
    /// the scan afterwards and to fill the logs), but the decision to take it, reject it or let it pass is made
    /// only from the scan answer: the cell never reads TrueKind / TrueDefect to decide.
    /// </summary>
    public sealed class PackingItem : MonoBehaviour
    {
        public int Serial;
        public ItemKind TrueKind;
        public ItemDefect TrueDefect;
        /// <summary>Approximate size (m) of the item, used to place it in a carton.</summary>
        public float Size = .14f;

        // ---- scan result (from Meta), the only thing the cell decides on
        public bool Scanned, Scanning;
        public string ScanKind = "";
        public string ScanDefect = "";
        public float ScanConfidence;
        public string ScanModel = "";
        public string ScanReason = "";
        public bool ScanFailed;

        /// <summary>take (into a carton) / reject (bin) / pass (another lap).</summary>
        public string Decision = "";
        public int Laps;

        public static string KindName(ItemKind k)
        {
            switch (k)
            {
                case ItemKind.Mug: return "mug";
                case ItemKind.Bottle: return "bottle";
                case ItemKind.Can: return "can";
                case ItemKind.Ball: return "ball";
                case ItemKind.ToyCar: return "toy car";
                case ItemKind.Book: return "book";
                default: return "gift box";
            }
        }

        public static string DefectName(ItemDefect d)
        {
            switch (d)
            {
                case ItemDefect.Cracked: return "cracked";
                case ItemDefect.Dented: return "dented";
                case ItemDefect.Stained: return "stained";
                case ItemDefect.Broken: return "broken";
                default: return "none";
            }
        }

        public static readonly string[] KindNames = { "mug", "bottle", "can", "ball", "toy car", "book", "gift box" };
        public static readonly string[] DefectNames = { "none", "cracked", "dented", "stained", "broken" };

        public static bool TryParseKind(string s, out ItemKind kind)
        {
            s = (s ?? "").Trim().ToLowerInvariant().Replace("_", " ");
            for (int i = 0; i < KindNames.Length; i++)
                if (s == KindNames[i]) { kind = (ItemKind)i; return true; }
            kind = ItemKind.GiftBox;
            return false;
        }
    }

    /// <summary>
    /// Builds the small products from simple shapes (100 % generated by code, identical in the full and the public
    /// project). The sequence is reproducible: the same seed gives the same items in the same order, which lets the
    /// RECORDED DEMO replay the scan answers of a recorded run.
    /// </summary>
    public static class PackingItemFactory
    {
        private static readonly Dictionary<int, Material> materials = new Dictionary<int, Material>();
        private static Shader litShader;

        private static readonly Color[] Palette =
        {
            new Color(.85f, .22f, .2f), new Color(.2f, .45f, .85f), new Color(.95f, .75f, .15f), new Color(.25f, .65f, .35f),
            new Color(.9f, .9f, .88f), new Color(.55f, .3f, .7f), new Color(.95f, .5f, .15f), new Color(.15f, .6f, .65f)
        };

        public static PackingItem Create(int serial, System.Random rng, float defectRate, Transform parent)
        {
            // three products on the line: bottles (carton A), mugs (carton B), balls (carton C)
            ItemKind kind = new[] { ItemKind.Bottle, ItemKind.Mug, ItemKind.Ball }[rng.Next(0, 3)];
            ItemDefect defect = rng.NextDouble() < defectRate ? (ItemDefect)rng.Next(1, 5) : ItemDefect.None;
            Color color = Palette[rng.Next(0, Palette.Length)];
            Color accent = Palette[rng.Next(0, Palette.Length)];
            var root = new GameObject("item_" + serial.ToString("000") + "_" + PackingItem.KindName(kind).Replace(' ', '_'));
            if (parent != null) root.transform.SetParent(parent, false);
            var item = root.AddComponent<PackingItem>();
            item.Serial = serial;
            item.TrueKind = kind;
            item.TrueDefect = defect;
            Build(root.transform, kind, defect, color, accent, rng, out item.Size);
            return item;
        }

        // ------------------------------------------------------------------ shapes (origin = bottom centre)

        private static void Build(Transform root, ItemKind kind, ItemDefect defect, Color c, Color a, System.Random rng, out float size)
        {
            Transform removable = null;
            switch (kind)
            {
                case ItemKind.Mug:
                    Part(root, PrimitiveType.Cylinder, new Vector3(0f, .055f, 0f), new Vector3(.1f, .055f, .1f), c);
                    Part(root, PrimitiveType.Cylinder, new Vector3(0f, .108f, 0f), new Vector3(.082f, .003f, .082f), Color.Lerp(c, Color.black, .6f));
                    removable = Handle(root, new Vector3(.065f, .055f, 0f), c);
                    size = .14f;
                    break;
                case ItemKind.Bottle:
                    Part(root, PrimitiveType.Cylinder, new Vector3(0f, .07f, 0f), new Vector3(.07f, .07f, .07f), c, .7f);
                    removable = Part(root, PrimitiveType.Cylinder, new Vector3(0f, .17f, 0f), new Vector3(.03f, .03f, .03f), c, .7f);
                    Part(removable, PrimitiveType.Cylinder, new Vector3(0f, 1.2f, 0f), new Vector3(1.25f, .35f, 1.25f), a);
                    Part(root, PrimitiveType.Cube, new Vector3(0f, .07f, 0f), new Vector3(.072f, .05f, .072f), Color.white, .1f);
                    size = .12f;
                    break;
                case ItemKind.Can:
                    Part(root, PrimitiveType.Cylinder, new Vector3(0f, .06f, 0f), new Vector3(.068f, .06f, .068f), c, .85f, .8f);
                    Part(root, PrimitiveType.Cylinder, new Vector3(0f, .121f, 0f), new Vector3(.06f, .002f, .06f), new Color(.75f, .75f, .78f), .8f, .9f);
                    removable = Part(root, PrimitiveType.Cube, new Vector3(.012f, .124f, 0f), new Vector3(.025f, .003f, .012f), new Color(.8f, .8f, .82f), .8f, .9f);
                    size = .1f;
                    break;
                case ItemKind.Ball:
                    Part(root, PrimitiveType.Sphere, new Vector3(0f, .06f, 0f), new Vector3(.12f, .12f, .12f), c, .4f);
                    removable = Part(root, PrimitiveType.Cylinder, new Vector3(0f, .06f, 0f), new Vector3(.122f, .008f, .122f), a, .4f);
                    size = .13f;
                    break;
                case ItemKind.ToyCar:
                    Part(root, PrimitiveType.Cube, new Vector3(0f, .04f, 0f), new Vector3(.16f, .045f, .08f), c, .5f);
                    Part(root, PrimitiveType.Cube, new Vector3(-.01f, .075f, 0f), new Vector3(.08f, .035f, .07f), Color.Lerp(a, Color.white, .5f), .6f);
                    Transform wheel = null;
                    foreach (float x in new[] { -.05f, .05f })
                        foreach (float z in new[] { -.042f, .042f })
                        {
                            Transform w = Part(root, PrimitiveType.Cylinder, new Vector3(x, .02f, z), new Vector3(.04f, .006f, .04f), new Color(.08f, .08f, .08f));
                            w.localRotation = Quaternion.Euler(90f, 0f, 0f);
                            wheel = w;
                        }
                    removable = wheel;
                    size = .17f;
                    break;
                case ItemKind.Book:
                    Part(root, PrimitiveType.Cube, new Vector3(0f, .022f, 0f), new Vector3(.15f, .044f, .11f), c, .3f);
                    Part(root, PrimitiveType.Cube, new Vector3(.003f, .022f, 0f), new Vector3(.146f, .036f, .104f), new Color(.95f, .94f, .88f));
                    removable = Part(root, PrimitiveType.Cube, new Vector3(-.01f, .045f, 0f), new Vector3(.08f, .002f, .05f), a);
                    size = .16f;
                    break;
                default: // gift box with a ribbon
                    Part(root, PrimitiveType.Cube, new Vector3(0f, .05f, 0f), new Vector3(.11f, .1f, .11f), c, .3f);
                    Part(root, PrimitiveType.Cube, new Vector3(0f, .05f, 0f), new Vector3(.112f, .102f, .025f), a, .5f);
                    Part(root, PrimitiveType.Cube, new Vector3(0f, .05f, 0f), new Vector3(.025f, .102f, .112f), a, .5f);
                    removable = Part(root, PrimitiveType.Sphere, new Vector3(0f, .108f, 0f), new Vector3(.04f, .025f, .04f), a, .5f);
                    size = .13f;
                    break;
            }
            ApplyDefect(root, defect, removable, rng);
        }

        /// <summary>Defects are drawn to be visible from above (scan camera).</summary>
        private static void ApplyDefect(Transform root, ItemDefect defect, Transform removable, System.Random rng)
        {
            float top = TopOf(root);
            switch (defect)
            {
                case ItemDefect.Cracked:
                    // dark jagged crack lines across the top and the side
                    for (int i = 0; i < 4; i++)
                    {
                        Transform crack = Part(root, PrimitiveType.Cube, new Vector3(-.03f + i * .02f, top + .0015f, -.02f + (i % 2) * .02f),
                                               new Vector3(.035f, .003f, .004f), new Color(.05f, .04f, .04f));
                        crack.localRotation = Quaternion.Euler(0f, 35f + i * 50f * (i % 2 == 0 ? 1 : -1), 0f);
                    }
                    break;
                case ItemDefect.Dented:
                    // crushed: flattened and sheared, with a darker dent
                    root.localScale = new Vector3(1.15f, .72f, .9f);
                    Part(root, PrimitiveType.Sphere, new Vector3(.02f, top * .95f, .01f), new Vector3(.05f, .012f, .04f), new Color(0f, 0f, 0f), .1f)
                        .GetComponent<Renderer>().sharedMaterial = Mat(new Color(.12f, .1f, .09f), .1f, 0f);
                    break;
                case ItemDefect.Stained:
                    for (int i = 0; i < 3; i++)
                    {
                        float s = .025f + .015f * (float)rng.NextDouble();
                        Part(root, PrimitiveType.Sphere, new Vector3(-.03f + .03f * i, top + .001f, -.015f + .015f * (i % 2)),
                             new Vector3(s, .004f, s * .8f), new Color(.32f, .2f, .08f), .05f);
                    }
                    break;
                case ItemDefect.Broken:
                    // a part is missing and the item lies tilted, with a jagged dark break
                    if (removable != null) UnityEngine.Object.Destroy(removable.gameObject);
                    Part(root, PrimitiveType.Cube, new Vector3(.03f, top * .7f, 0f), new Vector3(.03f, .02f, .03f), new Color(.08f, .07f, .06f))
                        .localRotation = Quaternion.Euler(30f, 20f, 45f);
                    root.localRotation = Quaternion.Euler(0f, 0f, 12f);
                    break;
            }
        }

        private static float TopOf(Transform root)
        {
            float top = 0f;
            foreach (Renderer r in root.GetComponentsInChildren<Renderer>())
                top = Mathf.Max(top, root.InverseTransformPoint(r.bounds.max).y);
            return top;
        }

        private static Transform Handle(Transform root, Vector3 at, Color c)
        {
            var h = new GameObject("handle").transform;
            h.SetParent(root, false);
            h.localPosition = at;
            Part(h, PrimitiveType.Cube, new Vector3(.012f, .03f, 0f), new Vector3(.01f, .012f, .012f), c);
            Part(h, PrimitiveType.Cube, new Vector3(.012f, -.03f, 0f), new Vector3(.01f, .012f, .012f), c);
            Part(h, PrimitiveType.Cube, new Vector3(.02f, 0f, 0f), new Vector3(.01f, .07f, .012f), c);
            return h;
        }

        private static Transform Part(Transform parent, PrimitiveType type, Vector3 localPos, Vector3 localScale, Color color,
                                      float smoothness = .35f, float metallic = 0f)
        {
            GameObject go = GameObject.CreatePrimitive(type);
            Collider col = go.GetComponent<Collider>();
            if (col != null) UnityEngine.Object.Destroy(col);
            go.transform.SetParent(parent, false);
            go.transform.localPosition = localPos;
            go.transform.localScale = localScale;
            var r = go.GetComponent<Renderer>();
            r.sharedMaterial = Mat(color, smoothness, metallic);
            r.shadowCastingMode = UnityEngine.Rendering.ShadowCastingMode.On;
            return go.transform;
        }

        public static Material Mat(Color color, float smoothness, float metallic)
        {
            int key = Mathf.RoundToInt(color.r * 255) << 24 ^ Mathf.RoundToInt(color.g * 255) << 16 ^ Mathf.RoundToInt(color.b * 255) << 8 ^
                      Mathf.RoundToInt(smoothness * 15) << 4 ^ Mathf.RoundToInt(metallic * 15);
            if (materials.TryGetValue(key, out Material m) && m != null) return m;
            if (litShader == null) litShader = Shader.Find("Universal Render Pipeline/Lit") ?? Shader.Find("Standard");
            m = new Material(litShader) { name = "packing_item" };
            if (m.HasProperty("_BaseColor")) m.SetColor("_BaseColor", color);
            if (m.HasProperty("_Color")) m.SetColor("_Color", color);
            if (m.HasProperty("_Smoothness")) m.SetFloat("_Smoothness", smoothness);
            if (m.HasProperty("_Glossiness")) m.SetFloat("_Glossiness", smoothness);
            if (m.HasProperty("_Metallic")) m.SetFloat("_Metallic", metallic);
            materials[key] = m;
            return m;
        }
    }
}
